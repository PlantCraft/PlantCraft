import threading

import pytest

from histcraft.archive.store import ArchiveStore
from histcraft.catalog.models import PointIn, SourceIn
from histcraft.catalog.store import CatalogStore
from histcraft.config import Settings
from histcraft.db import (
    Database,
    ReadTimeout,
    _postgres_schema,
    _postgres_sql,
    read_timeout,
    safe_url,
)
from tests.conftest import database, make_settings, postgres_only


def test_sql_is_translated_for_postgresql():
    assert _postgres_sql("SELECT * FROM points WHERE tag LIKE ? AND id = :id") == (
        "SELECT * FROM points WHERE tag ILIKE %s AND id = %(id)s"
    )
    schema = _postgres_schema(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, at INTEGER, v {ANY},"
        " x REAL, data BLOB) WITHOUT ROWID;"
    )
    assert schema == (
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at BIGINT,"
        " v JSONB, x DOUBLE PRECISION, data BYTEA);"
    )


def test_urls_are_shown_without_their_password():
    assert safe_url("postgresql://hist:s3cret@db:5432/histcraft") == (
        "postgresql://hist:***@db:5432/histcraft"
    )
    assert safe_url("postgresql://hist@db/histcraft") == "postgresql://hist@db/histcraft"
    assert Database("postgresql://hist:s3cret@db/h").describe() == "postgresql://hist:***@db/h"


def test_the_password_comes_from_its_file(tmp_path, monkeypatch):
    (tmp_path / "pw").write_text("s3cret\n")
    monkeypatch.setenv("HISTCRAFT_DATABASE_URL", "postgresql://hist@db:5432/histcraft")
    monkeypatch.setenv("HISTCRAFT_DATABASE_PASSWORD_FILE", str(tmp_path / "pw"))
    settings = Settings.from_environment()
    assert settings.config_target == settings.archive_target == settings.database_url
    assert settings.database_password() == "s3cret"
    assert "s3cret" not in repr(settings)
    assert Settings(data_dir=tmp_path).archive_target == tmp_path / "archive.sqlite3"


def test_snapshots_keep_numbers_and_texts(tmp_path):
    archive = ArchiveStore(database(tmp_path))
    archive.put_snapshots(
        [
            {"point": 1, "ts": 1000, "value": 21.5, "status": "ok"},
            {"point": 2, "ts": 1000, "value": "AUTO", "status": "ok"},
            {"point": 3, "ts": 1000, "value": float("nan"), "status": "bad"},
            {"point": 4, "ts": None, "value": None, "status": "waiting"},
        ]
    )
    snaps = archive.snapshots()
    assert [snaps[p]["value"] for p in (1, 2, 3, 4)] == [21.5, "AUTO", None, None]
    assert archive.file_bytes() > 0


def test_search_is_case_blind_and_conflicts_skip(tmp_path):
    catalog = CatalogStore(database(tmp_path, "config"))
    catalog.save_source(SourceIn(id="pc", name="Plant", endpoint="opc.tcp://plc:4840"), create=True)
    first = catalog.add_points(
        [
            PointIn(tag="TI-100.PV", source_id="pc", address="a", description="Reactor inlet"),
            PointIn(tag="TI-100.PV", source_id="pc", address="b"),
            PointIn(tag="TI-101.PV", source_id="pc", address="a"),
        ]
    )
    assert first["added"] == ["pc:TI-100.PV"] and len(first["skipped"]) == 2
    assert [p["tag"] for p in catalog.points(q="reactor")] == ["TI-100.PV"]
    assert catalog.add_request("browse", "pc", "admin") < catalog.add_request("test", "pc", "x")


@postgres_only
def test_server_and_collector_write_at_the_same_time(tmp_path):
    """Two processes in the suite, two ``Database`` objects here: no 'database is locked'."""

    settings = make_settings(tmp_path)
    catalog = CatalogStore(Database(settings.config_target))
    archive = ArchiveStore(Database(settings.archive_target))
    catalog.save_source(SourceIn(id="pc", name="Plant", endpoint="opc.tcp://plc:4840"), create=True)
    errors: list[Exception] = []

    def collect() -> None:
        try:
            for second in range(200):
                archive.append({p: ("number", [(second * 1000, float(second))]) for p in range(20)})
        except Exception as exc:  # noqa: BLE001 - reported below
            errors.append(exc)

    def configure() -> None:
        try:
            for index in range(100):
                catalog.add_points([PointIn(tag=f"P{index}", source_id="pc", address=f"a{index}")])
        except Exception as exc:  # noqa: BLE001
            errors.append(exc)

    threads = [threading.Thread(target=collect), threading.Thread(target=configure)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    assert not errors
    assert len(catalog.points()) == 100
    assert archive.point_stats()[7]["values"] == 200


@postgres_only
def test_a_read_past_its_time_limit_is_cancelled(tmp_path):
    db = database(tmp_path)
    with pytest.raises(ReadTimeout), read_timeout(0.2), db.connect() as connection:
        connection.execute("SELECT pg_sleep(2)")
    # The pooled connection comes back without the limit.
    with db.connect() as connection:
        connection.execute("SELECT pg_sleep(0.3)")


def test_a_read_too_long_answers_504(runtime, client, monkeypatch):
    runtime.catalog.save_source(
        SourceIn(id="plant", name="Plant", endpoint="opc.tcp://127.0.0.1:4840/"), create=True
    )
    runtime.catalog.add_points([PointIn(tag="TI-1", source_id="plant")])

    def slow(*_args, **_kwargs):
        raise ReadTimeout(runtime.settings.query_timeout)

    monkeypatch.setattr(runtime.reader, "series", slow)
    response = client.get("/hist/api/points/plant:TI-1/series")
    assert response.status_code == 504
    assert response.json()["detail"] == (
        "This read took longer than 30 s: ask for a shorter period or a larger step."
    )
