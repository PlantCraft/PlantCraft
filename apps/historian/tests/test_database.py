"""The database layer: one SQL for SQLite and PostgreSQL, and PostgreSQL's own needs.

Every other test runs on PostgreSQL too when ``HISTCRAFT_TEST_DATABASE_URL`` is set; these
check what the two engines would otherwise do differently.
"""

